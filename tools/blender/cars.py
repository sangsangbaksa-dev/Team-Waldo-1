def wheel(b: B, x: float, y: float, r: float = 0.34, w: float = 0.24, rim: str = 'Steel') -> None:
    s = 1 if y > 0 else -1
    b.cyl((x, y, r), r, w, 'Rubber', axis='y', seg=18)
    b.cyl((x, y + s * (w / 2 - 0.02), r), r * 0.62, 0.05, rim, axis='y', seg=14)
    b.cyl((x, y + s * (w / 2 + 0.01), r), r * 0.2, 0.05, 'Gunmetal', axis='y', seg=8)
    for k in range(5):
        a = k * 2 * math.pi / 5
        b.box((x + math.cos(a) * r * 0.36, y + s * (w / 2 + 0.01), r + math.sin(a) * r * 0.36), (0.035, 0.03, r * 0.42), 'Gunmetal', rot=None)
    b.cyl((x, y - s * 0.06, r), r * 1.18, 0.1, 'Black', axis='y', seg=18)     # 휠 하우스 그림자


def car(kind: str, paint: str = 'Paint') -> B:
    sp = SPEC['sedan' if kind in ('police', 'taxi') else kind]
    L, W = sp['L'], sp['W']
    b = B()
    b.loft(sp['body'], paint)
    cab = sp['cab']
    b.loft([(x, zb, zt - 0.05 if zt > 1.3 else zt, hw) for x, zb, zt, hw in cab], 'Glass')
    if kind != 'van':
        (x1, _, z1, h1), (x2, _, z2, h2) = cab[1], cab[2]
        b.loft([(x1 - 0.12, z1 - 0.13, z1 - 0.03, h1 * 0.86), (x1 + 0.2, z1 - 0.1, z1 + 0.01, h1 * 0.97), (x2 - 0.2, z2 - 0.1, z2 + 0.01, h2 * 0.97), (x2 + 0.1, z2 - 0.13, z2 - 0.03, h2 * 0.86)], paint)
    # 범퍼·그릴
    b.box((L / 2 - 0.12, 0, 0.42), (0.2, W * 0.88, 0.22), 'Black', taper=(0.96, 0.98))
    b.box((-L / 2 + 0.1, 0, 0.42), (0.2, W * 0.88, 0.22), 'Black')
    b.box((L / 2 - 0.1, 0, 0.66), (0.08, 0.7, 0.16), 'Black')
    for k in (-1, 0, 1):
        b.box((L / 2 - 0.05, k * 0.2, 0.66), (0.04, 0.02, 0.15), 'Steel')
    b.box((L / 2 - 0.06, 0, 0.36), (0.04, 0.46, 0.12), 'White')              # 번호판
    b.box((-L / 2 + 0.03, 0, 0.5), (0.04, 0.46, 0.12), 'White')
    for s in (-1, 1):
        b.sphere((L / 2 - 0.14, s * (W / 2 - 0.34), 0.74 if kind != 'suv' else 0.88), 0.14, 'Glow', scale=(0.5, 1.5, 0.9), seg=10, rings=5)   # 헤드라이트
        b.sphere((-L / 2 + 0.1, s * (W / 2 - 0.3), 0.76), 0.12, 'GlowRed', scale=(0.5, 1.6, 0.8), seg=10, rings=5)                                  # 테일라이트
        b.box((0.65, s * (W / 2 + 0.1), sp['cab'][1][1] + 0.18), (0.14, 0.16, 0.12), paint)                                                      # 사이드미러
        for dx in (-0.5, 0.45):
            b.box((dx, s * (W / 2 - 0.01), 0.66), (0.02, 0.02, 0.5), 'Black') if kind not in ('van',) else None                                 # 도어 이음선
        b.box((0.1, s * (W / 2 + 0.005), 0.72), (0.18, 0.04, 0.035), 'Steel')                                                                     # 손잡이
        for x in (L * 0.3, -L * 0.3):
            wheel(b, x, s * (W / 2 - 0.1), 0.36 if kind in ('suv', 'van') else 0.33)
    if kind == 'sports':
        b.box((-L / 2 + 0.1, 0, 0.98), (0.36, W * 0.86, 0.05), 'Black')
        for s in (-1, 1):
            b.box((-L / 2 + 0.12, s * 0.7, 0.84), (0.06, 0.05, 0.28), 'Black')
        b.box((0.4, 0, 0.75), (L * 0.9, 0.3, 0.02), 'White')
        b.box((1.2, 0, 0.77), (0.8, 0.5, 0.04), 'Black', taper=(0.7, 0.7))
    if kind == 'suv':
        b.box((-0.2, 0, 1.78), (2.6, 0.06, 0.05), 'Steel')
        b.box((-0.2, 0.72, 1.78), (2.6, 0.06, 0.05), 'Steel').box((-0.2, -0.72, 1.78), (2.6, 0.06, 0.05), 'Steel')
    if kind == 'taxi':
        b.box((0.0, 0, 1.54), (0.7, 0.28, 0.2), 'Glow')
        b.box((0.0, 0, 1.46), (0.7, 0.3, 0.04), 'Black')
    if kind == 'police':
        b.box((0.0, 0, 0.62), (L * 0.78, W * 1.002, 0.32), 'White', taper=(1.0, 1.0))
        b.box((0.1, 0, 1.52), (0.5, 1.3, 0.06), 'Black')
    return b


