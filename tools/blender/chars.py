        sh.sphere((0.07 * w, 0, -0.44), 0.066, s.get('knee_mat', 'Gunmetal'), scale=(0.62, 1.0, 1.15), seg=8, rings=5)
        sh.stack([(-0.5, 0.01, 0, 0.076 * w, 0.076), (-0.475, 0.012, 0, 0.076 * w, 0.076)], 'Black', n=10, sq=2.4, cap=False)
