def _hair(b: B, style: str, hc: str) -> None:
    if style in ('none', 'bald'):
        return
    if style == 'balding':
        b.stack([(1.63, -0.04, 0, 0.09, 0.112), (1.74, -0.035, 0, 0.11, 0.115), (1.77, -0.04, 0, 0.095, 0.108)], hc, n=12, sq=2.3)
        return
    if style == 'afro':
        b.sphere((-0.02, 0, 1.78), 0.175, hc, scale=(1.0, 1.02, 0.9), seg=10, rings=7)
        return
    r = 0.97 if style == 'buzz' else 1.0
    b.stack([(1.735, -0.032, 0, 0.127 * r, 0.114 * r), (1.795, -0.01, 0, 0.128 * r, 0.11 * r), (1.84, -0.01, 0, 0.094 * r, 0.082 * r), (1.862 if r == 1.0 else 1.85, -0.012, 0, 0.035, 0.03)], hc, n=12, sq=2.3)
    b.stack([(1.61, -0.065, 0, 0.065, 0.085), (1.68, -0.055, 0, 0.09, 0.108 * r), (1.745, -0.045, 0, 0.108, 0.114 * r)], hc, n=12, sq=2.3)                    # 뒷머리
    if style == 'buzz' or style == 'under':
        return
    if style in ('short', 'side', 'ponytail', 'bun', 'long', 'bob'):
        b.box((0.085, 0.01 if style != 'side' else 0.03, 1.806), (0.07, 0.19, 0.045), hc, taper=(0.9, 0.9), rot=None, off=(0.012, 0.0))            # 앞머리
    if style == 'side':
        b.box((0.05, 0.085, 1.79), (0.14, 0.06, 0.06), hc)
    if style == 'quiff':
        b.box((0.07, 0, 1.845), (0.11, 0.15, 0.07), hc, taper=(0.8, 0.8), off=(0.03, 0))
    if style == 'mohawk':
        b.box((-0.02, 0, 1.87), (0.24, 0.04, 0.08), hc, taper=(0.8, 1.0))
    if style == 'long':
        b.stack([(1.38, -0.09, 0, 0.045, 0.115), (1.55, -0.085, 0, 0.065, 0.13), (1.7, -0.06, 0, 0.09, 0.124), (1.76, -0.05, 0, 0.1, 0.118)], hc, n=12, sq=2.4)
        for y in (-1, 1):
            b.tube([((0.04, y * 0.112, 1.76), 0.03), ((0.05, y * 0.118, 1.62), 0.032), ((0.07, y * 0.13, 1.47), 0.022)], hc, n=6)
    if style == 'bob':
        b.stack([(1.56, -0.045, 0, 0.115, 0.135), (1.66, -0.045, 0, 0.115, 0.128), (1.75, -0.04, 0, 0.11, 0.118)], hc, n=12, sq=2.4)
    if style == 'ponytail':
        b.sphere((-0.135, 0, 1.775), 0.045, hc, seg=8, rings=5)
        b.tube([((-0.14, 0, 1.775), 0.04), ((-0.21, 0, 1.72), 0.05), ((-0.225, 0, 1.58), 0.042), ((-0.2, 0, 1.46), 0.015)], hc, n=8)
    if style == 'bun':
        b.sphere((-0.08, 0, 1.86), 0.062, hc, seg=8, rings=5)


