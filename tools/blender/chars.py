        h = s['hardhat']
        b.stack([(1.76, 0.0, 0, 0.15, 0.135), (1.81, 0.0, 0, 0.145, 0.13), (1.86, -0.002, 0, 0.115, 0.102), (1.89, -0.004, 0, 0.06, 0.052), (1.9, -0.004, 0, 0.02, 0.018)], h, n=14, sq=2.2)
