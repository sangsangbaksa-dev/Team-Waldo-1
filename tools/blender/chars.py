    pants, boots, bulk = s.get('pants', 'Black'), s.get('boots', 'Black'), s.get('bulk', 1.0)
    w = 1.0 + (bulk - 1.0) * 0.7
    leg, sh = B(), B()
    if s.get('legs') == 'slim':     # 치마·원피스 아래로 보이는 다리
        leg.stack([(0.02, 0, 0, 0.085, 0.085), (-0.25, 0.004, 0, 0.074, 0.074), (-0.45, 0.012, 0, 0.056, 0.056)], pants, n=10, sq=2.2)
        leg.sphere((0.012, 0, -KNEE), 0.05, pants, seg=8, rings=5)
        sh.stack([(-0.42, 0.012, 0, 0.056, 0.056), (-0.56, -0.004, 0, 0.06, 0.058), (-0.74, 0, 0, 0.042, 0.042), (-0.8, 0, 0, 0.044, 0.044)], pants, n=10, sq=2.2)
    else:
        leg.stack([(0.03, 0, 0, 0.1 * w, 0.098), (-0.08, 0, 0, 0.106 * w, 0.1), (-0.26, 0.006, 0, 0.092 * w, 0.09), (-0.41, 0.016, 0, 0.074 * w, 0.074), (-0.46, 0.014, 0, 0.07 * w, 0.07)], pants, n=10, sq=2.4)
