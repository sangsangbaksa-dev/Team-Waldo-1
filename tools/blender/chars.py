        sh.stack([(-0.83, 0.0, 0, 0.072 * w, 0.068), (-0.7, 0.0, 0, 0.074 * w, 0.07), (-0.66, 0.0, 0, 0.076 * w, 0.073)], boots, n=10, sq=2.6)
