def _arm(b: B, sh, el, hand, s: dict, bulk: float) -> None:
    sleeve, sl = s.get('sleeve', s['shirt']), s.get('sleeve_len', 'long')
    S, E, H = Vector(sh), Vector(el), Vector(hand)
    W = H - (H - E).normalized() * 0.045
    r0, r1, r2 = 0.06 * bulk, 0.049 * bulk, 0.039 * bulk
    hm = s.get('gloves') or 'Skin'
    if sl == 'none':
        b.sphere(S, 0.066 * bulk, 'Skin', seg=8, rings=5)
        b.tube([(S, r0 * 0.95), (E, r1), (W, r2)], 'Skin', n=8)
    elif sl == 'short':
        M = S + (E - S) * 0.6
        b.sphere(S, 0.065 * bulk, sleeve, seg=8, rings=5)
        b.tube([(S, r0 * 1.12), (M, r0 * 1.1)], sleeve, n=8)
        b.tube([(M, r0 * 0.9), (E, r1), (W, r2)], 'Skin', n=8)
    elif sl == 'rolled':
        b.sphere(S, 0.065 * bulk, sleeve, seg=8, rings=5)
        b.tube([(S, r0 * 1.05), (E, r1 * 1.12)], sleeve, n=8)
        b.sphere(E, r1 * 1.22, sleeve, seg=8, rings=4)
        b.tube([(E, r1 * 0.95), (W, r2)], 'Skin', n=8)
    else:
        b.sphere(S, 0.065 * bulk, sleeve, seg=8, rings=5)
        b.tube([(S, r0 * 1.05), (E, r1 * 1.1), (W, r2 * 1.12)], sleeve, n=8)
        if s.get('cuff'):
            b.tube([(W - (W - E).normalized() * 0.03, r2 * 1.25), (W, r2 * 1.25)], s['cuff'], n=8)
    if s.get('elbow'):
        b.sphere(E, r1 * 1.3, s['elbow'], scale=(1, 1, 1), seg=8, rings=4)
    if s.get('watch') and sl != 'none':
        pass
    b.sphere(H, 0.047 * min(bulk, 1.12), hm, scale=(1.0, 0.82, 1.0), seg=8, rings=5)


