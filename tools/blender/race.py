"""SPEED RUSH 전용 레이싱카 3종(gt, wide, long). Paint = 차체색, Team = 스트라이프·윙 등 보조색."""
import math

import bpy

from lib import B, export, reset

# 변형별 설정: L 길이, hw 차체 반폭 배율, body=(x, 하단, 상단, 반폭) 단면, wing=(높이, 폭 배율, 코드)
SPEC = {
    'gt': dict(L=4.7, k=1.0, body=[(-2.38, .3, .6, .72), (-2.25, .24, .76, .9), (-1.5, .2, .8, 1.0), (-0.3, .2, .72, 1.02), (0.9, .2, .62, 1.0), (1.8, .2, .5, .93), (2.38, .22, .4, .76)],
               cab=[(-1.35, .68, .92, .58), (-0.85, .68, 1.12, .7), (-0.05, .68, 1.12, .72), (0.75, .68, .78, .84)], wing=(1.02, 1.0, .42), flare=0.0),
    'wide': dict(L=4.7, k=1.06, body=[(-2.38, .3, .62, .76), (-2.25, .24, .78, .95), (-1.5, .2, .82, 1.06), (-0.3, .2, .74, 1.08), (0.9, .2, .64, 1.06), (1.8, .2, .52, .98), (2.38, .22, .4, .8)],
                 cab=[(-1.3, .7, .9, .56), (-0.85, .7, 1.08, .68), (-0.05, .7, 1.08, .7), (0.7, .7, .76, .84)], wing=(1.16, 1.08, .5), flare=0.07),
    'long': dict(L=4.7, k=0.98, body=[(-2.38, .3, .56, .7), (-2.25, .24, .72, .88), (-1.3, .2, .78, .98), (-0.2, .2, .7, 1.0), (1.0, .2, .6, .98), (1.95, .2, .46, .9), (2.4, .2, .36, .7)],
                 cab=[(-1.5, .66, .86, .52), (-0.95, .66, 1.06, .68), (-0.05, .66, 1.08, .7), (0.85, .66, .74, .84)], wing=(0.84, 0.9, .3), flare=0.0),
}


def wheel(b: B, x: float, y: float, r: float, w: float) -> None:
    s = 1 if y > 0 else -1
    b.cyl((x, y, r), r, w, 'Rubber', axis='y', seg=22)
    b.cyl((x, y + s * (w / 2 - 0.015), r), r * 0.72, 0.04, 'Steel', axis='y', seg=22)          # 림
    b.cyl((x, y + s * (w / 2 + 0.005), r), r * 0.5, 0.03, 'Gunmetal', axis='y', seg=22)
    for k in range(6):                                                                           # 스포크
        a = k * math.pi / 3
        b.box((x + math.cos(a) * r * 0.34, y + s * (w / 2 + 0.02), r + math.sin(a) * r * 0.34), (0.05, 0.03, r * 0.5), 'Steel', rot=None)
    b.cyl((x, y + s * (w / 2 + 0.03), r), r * 0.14, 0.03, 'Red', axis='y', seg=10)               # 센터 락
    b.box((x - r * 0.1, y - s * 0.02, r + r * 0.52), (r * 0.5, 0.05, r * 0.2), 'Red')            # 브레이크 캘리퍼
    b.cyl((x, y - s * 0.1, r), r * 1.04, 0.14, 'Black', axis='y', seg=22)                         # 휠 하우스 안쪽


def racer(kind: str) -> B:
    sp = SPEC[kind]
    L, k, flare = sp['L'], sp['k'], sp['flare']
    W = 2.0 * k
    b = B()
    b.loft(sp['body'], 'Paint', n=18, sq=3.4)
    cab = sp['cab']
    b.loft([(x, zb, zt - 0.04, hw) for x, zb, zt, hw in cab], 'Glass', n=16, sq=2.8)
    # 루프 패널(차체색)
    (x1, _, z1, h1), (x2, _, z2, h2) = cab[1], cab[2]
    b.loft([(x1 - 0.1, z1 - 0.12, z1 - 0.01, h1 * 0.84), (x1 + 0.2, z1 - 0.1, z1 + 0.015, h1 * 0.96), (x2 - 0.15, z2 - 0.1, z2 + 0.015, h2 * 0.96), (x2 + 0.05, z2 - 0.12, z2 - 0.02, h2 * 0.84)], 'Paint', n=16, sq=3.0)
    b.box((0.0, 0, z1 + 0.03), (x2 - x1 + 0.3, 0.2, 0.012), 'Team')                                    # 루프 스트라이프
    # 센터 스트라이프(후드 → 트렁크)
    b.box((1.55, 0, 0.568), (1.5, 0.34, 0.016), 'Team', taper=(0.95, 0.9))
    b.box((-1.7, 0, 0.805), (1.1, 0.34, 0.014), 'Team')
    # 프런트: 스플리터, 흡기구, 헤드라이트
    b.box((L / 2 - 0.06, 0, 0.1), (0.34, W * 0.9, 0.035), 'Black', taper=(0.9, 0.96))
    b.box((L / 2 - 0.12, 0, 0.3), (0.12, W * 0.62, 0.2), 'Black')
    b.box((L / 2 - 0.1, 0, 0.3), (0.1, W * 0.5, 0.03), 'Steel')
    for s in (-1, 1):
        b.box((L / 2 - 0.34, s * (W / 2 - 0.3), 0.5), (0.5, 0.52, 0.04), 'Black', taper=(0.85, 0.85))      # 헤드라이트 하우징
        b.box((L / 2 - 0.3, s * (W / 2 - 0.34), 0.51), (0.5, 0.4, 0.02), 'Glow', taper=(0.7, 0.9))
        b.box((L / 2 - 0.5, s * 0.34, 0.5), (0.4, 0.3, 0.02), 'Black')                                 # 후드 벤트
        b.box((0.9, s * (W / 2 + 0.04), 0.32), (1.6, 0.08, 0.08), 'Black')                              # 사이드 스커트
        b.box((-0.85, s * (W / 2 - 0.02), 0.5), (0.7, 0.07, 0.24), 'Black', taper=(0.9, 0.4))          # 측면 흡기구
        b.box((0.25, s * (W / 2 - 0.005), 0.58), (0.3, 0.025, 0.26), 'White')                             # 도어 넘버 원판
        b.cyl((0.25, s * (W / 2 + 0.01), 0.58), 0.14, 0.02, 'Black', axis='y', seg=12)
        b.box((0.55, s * (W / 2 - 0.06), 0.9), (0.15, 0.13, 0.07), 'Paint')                            # 사이드미러
        b.box((0.55, s * (W / 2 - 0.12), 0.84), (0.07, 0.07, 0.07), 'Black')
        if kind == 'wide':
            b.box((0.3, s * (W / 2 - 0.005), 0.44), (3.0, 0.04, 0.09), 'Team')                         # 사이드 스트라이프
            b.box((L / 2 - 0.3, s * (W / 2 - 0.1), 0.2), (0.4, 0.12, 0.14), 'Team')                      # 카나드
    # 리어: 범퍼, 디퓨저, 배기구, 테일램프 바
    b.box((-L / 2 + 0.08, 0, 0.2), (0.2, W * 0.7, 0.12), 'Black')
    for s in (-1, 1):
        b.cyl((-L / 2 - 0.02, s * 0.34, 0.32), 0.07, 0.14, 'Steel', axis='x', seg=10)
        b.box((-L / 2 + 0.1, s * (W / 2 - 0.36), 0.7), (0.06, 0.46, 0.06), 'GlowRed')
    b.box((-L / 2 + 0.08, 0, 0.7), (0.05, W * 0.46, 0.05), 'GlowRed')
    # 리어 윙: 받침대 두 개 + 윙 + 엔드 플레이트
    wz, ws, wc = sp['wing']
    if wz > 0.5:
        for s in (-1, 1):
            b.box((-L / 2 + 0.28, s * 0.5 * ws, 0.78 + (wz - 0.78) / 2), (0.14, 0.05, wz - 0.74), 'Black')
            b.box((-L / 2 + 0.22, s * 0.95 * ws, wz + 0.02), (wc + 0.18, 0.04, 0.22), 'Black')          # 엔드 플레이트
        b.box((-L / 2 + 0.25, 0, wz), (wc, 1.9 * ws, 0.05), 'Team', taper=(0.96, 1.0))
        b.box((-L / 2 + 0.38, 0, wz + 0.07), (wc * 0.45, 1.9 * ws, 0.03), 'Black')
    # 바퀴: 타이어를 더 넓고 낮게
    wr, ww = (0.35, 0.34) if kind != 'long' else (0.34, 0.3)
    for s in (-1, 1):
        wheel(b, L * 0.3, s * (W / 2 - 0.13), wr, ww)
        wheel(b, -L * 0.3, s * (W / 2 - 0.13), wr + 0.01, ww + 0.04)
    return b


def build_race(path: str) -> int:
    reset()
    objs = [racer(k).build(k, bevel=0.018) for k in ('gt', 'wide', 'long')]
    return export(path, objs)


